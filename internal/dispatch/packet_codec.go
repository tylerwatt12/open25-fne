const packetHeaderSize = 64

// PacketCodec is the trusted endpoint's native vocoder/crypto subprocess. It
// has no RF device or FNE connection. Keys are loaded from a private runtime
// file, never included in the per-frame protocol or browser configuration.
type PacketCodecOptions struct {
	Binary  string
	KeyFile string // "-" enables clear vocoding with no key inventory.
}
type packetCodecTarget struct {
	frame       Frame
	encoderTail *Frame
}
type PacketCodec struct {
	options    PacketCodecOptions
	mu         sync.Mutex
	gate       chan struct{}
	command    *exec.Cmd
	input      io.WriteCloser
	output     *bufio.Reader
	outputPipe io.ReadCloser
	done       chan struct{}
	closed     bool
	closeOnce  sync.Once
	closeError error
	calls      map[string]map[[2]int]packetCodecTarget
}

func NewPacketCodec(options PacketCodecOptions) (*PacketCodec, error) {
	if !filepath.IsAbs(options.Binary) {
		return nil, errors.New("native packet codec requires an absolute executable path")
	}
	info, err := os.Stat(options.Binary)
	if err != nil || !info.Mode().IsRegular() || info.Mode().Perm()&0111 == 0 {
		return nil, errors.New("native packet codec executable is unavailable")
	}
	if options.KeyFile != "-" {
		info, err = os.Lstat(options.KeyFile)
		if !filepath.IsAbs(options.KeyFile) || err != nil || !info.Mode().IsRegular() || info.Mode().Perm()&0077 != 0 {
			return nil, errors.New("native packet codec requires an owner-only regular key file")
		}
	}
	return &PacketCodec{options: options, gate: make(chan struct{}, 1), calls: map[string]map[[2]int]packetCodecTarget{}}, nil
}

func (c *PacketCodec) Start(ctx context.Context) error {
	if err := c.startProcess(ctx); err != nil {
		return err
	}
	// The round trip confirms the native process has loaded its private keys
	// before the owner removes the runtime key file or advertises readiness.
	_, err := c.transform(ctx, 1, Frame{CallID: "codec-initialize", SourceID: 1, TalkgroupID: 1, AlgorithmID: 0x80, End: true})
	if err != nil {
		_ = c.Close()
		return errors.New("native packet codec did not become ready")
	}
	return nil
}
func (c *PacketCodec) startProcess(ctx context.Context) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.closed || c.command != nil {
		return errors.New("native packet codec is already started or closed")
	}
	command := exec.Command(c.options.Binary, "--packet-codec", c.options.KeyFile)
	command.SysProcAttr = codecProcessAttributes()
	input, err := command.StdinPipe()
	if err != nil {
		return err
	}
	output, err := command.StdoutPipe()
	if err != nil {
		input.Close()
		return err
	}
	// Diagnostics never include traffic key material and cannot corrupt the
	// binary response channel. The caller receives a bounded generic failure.
	command.Stderr = io.Discard
	if err = command.Start(); err != nil {
		input.Close()
		output.Close()
		return errors.New("native packet codec could not start")
	}
	c.command, c.input, c.output, c.outputPipe, c.done = command, input, bufio.NewReader(output), output, make(chan struct{})
	go func() { _ = command.Wait(); close(c.done) }()
	return nil
}

// Encode converts a clear 20ms PCM frame to clear or supported encrypted IMBE. The caller
// supplies authorized AlgorithmID/KeyID, not key bytes. Encryption MI and voice index
// are generated by the native endpoint. No plaintext is returned as ciphertext.
func (c *PacketCodec) Encode(ctx context.Context, frame Frame) (Frame, error) {
	if !frame.End && (len(frame.PCM) != FrameBytes || len(frame.Encoded) != 0) {
		return Frame{}, errors.New("packet codec encoding requires a 20 ms PCM frame")
	}
	if frame.AlgorithmID == 0 && !frame.Encrypted {
		frame.AlgorithmID = 0x80
	}
	if !frame.End && ((frame.AlgorithmID != 0x80 && !p25crypto.Supported(int(frame.AlgorithmID))) || (p25crypto.Supported(int(frame.AlgorithmID)) && !frame.Encrypted) || (frame.AlgorithmID == 0x80 && (frame.KeyID != 0 || frame.Encrypted))) {
		return Frame{}, errors.New("packet codec encryption parameters are invalid")
	}
	// PCM is generated at this trusted endpoint: compose its approved E/P
	// flags while preserving the caller's explicit priority/reserved policy.
	frame.ServiceOptions &^= 0xC0
	if frame.Emergency {
		frame.ServiceOptions |= 0x80
	}
	if frame.Encrypted {
		frame.ServiceOptions |= 0x40
	}
	frame.MessageIndicator, frame.P25 = nil, nil
	result, err := c.transform(ctx, 1, frame)
	if err != nil {
		return Frame{}, err
	}
	if !result.MediaValid() {
		return Frame{}, errors.New("native packet codec returned invalid encoded voice")
	}
	c.remember(result, true)
	return result, nil
}

// Decode produces clear PCM only at the trusted endpoint. The caller retains
// the input's algorithm/key metadata for received-security indications/audit.
func (c *PacketCodec) Decode(ctx context.Context, frame Frame) (Frame, error) {
	if !frame.MediaValid() || (!frame.End && len(frame.Encoded) != 11) {
		return Frame{}, errors.New("packet codec decoding requires valid encoded voice")
	}
	result, err := c.transform(ctx, 2, frame)
	if err != nil {
		if errors.Is(err, ErrP25SynchronizationPending) {
			c.remember(frame, false) // Pending native state still needs explicit End.
		}
		return Frame{}, err
	}
	c.remember(frame, false)
	result.Encrypted, result.AlgorithmID, result.KeyID = false, 0, 0
	result.ServiceOptions &^= 0x40
	result.MessageIndicator, result.VoiceIndex, result.P25 = nil, 0, nil
	if !result.MediaValid() {
		return Frame{}, errors.New("native packet codec returned invalid PCM")
	}
	return result, nil
}

// Finish returns at most eight encoded silence frames per target, allowing the
// keyless Site to complete its final LDU without inventing encrypted audio.
// The caller writes these frames before releasing the RF grant.
func (c *PacketCodec) Finish(ctx context.Context, callID string) ([]Frame, error) {
	c.mu.Lock()
	targets := []Frame{}
	for _, target := range c.calls[callID] {
		if target.encoderTail != nil {
			targets = append(targets, *target.encoderTail)
		}
	}
	c.mu.Unlock()
	out := []Frame{}
	for _, f := range targets {
		for f.VoiceIndex%9 != 8 {
			f.Sequence++
			f.PCM = make([]byte, FrameBytes)
			f.Encoded, f.P25 = nil, nil
			f.CapturedAt = time.Now()
			encoded, err := c.Encode(ctx, f)
			if err != nil {
				return nil, err
			}
			out = append(out, encoded)
			f = encoded
		}
	}
	return out, nil
}
func (c *PacketCodec) remember(frame Frame, encoded bool) {
	if frame.End {
		c.mu.Lock()
		delete(c.calls, frame.CallID)
		c.mu.Unlock()
		return
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.calls[frame.CallID] == nil {
		c.calls[frame.CallID] = map[[2]int]packetCodecTarget{}
	}
	identity := [2]int{frame.SourceID, frame.TalkgroupID}
	target := c.calls[frame.CallID][identity]
	if frame.Sequence >= target.frame.Sequence {
		frame.P25 = frame.P25.Clone()
		target.frame = frame
	}
	// Delayed loopback decoding must not rewind the encoder's continuation.
	if encoded && (target.encoderTail == nil || frame.Sequence > target.encoderTail.Sequence) {
		tail := frame
		tail.P25 = frame.P25.Clone()
		target.encoderTail = &tail
	}
	c.calls[frame.CallID][identity] = target
}

// End removes all native codec state for this call. It does not send RF audio.
func (c *PacketCodec) End(ctx context.Context, callID string) error {
	c.mu.Lock()
	targets := []Frame{}
	for _, target := range c.calls[callID] {
		targets = append(targets, target.frame)
	}
	delete(c.calls, callID)
	c.mu.Unlock()
	for _, f := range targets {
		f.End = true
		f.PCM = nil
		f.Encoded, f.P25 = nil, nil
		if _, err := c.transform(ctx, 1, f); err != nil {
			return err
		}
	}
	return nil
}

// EncodeOpaqueCodecPacket carries an already vocoded P25 frame. This interface
// contains no traffic keys and the Site does not turn it into plaintext.
func EncodeOpaqueCodecPacket(frame Frame) ([]byte, error) {
	if !frame.End && frame.P25 == nil {
		return nil, ErrP25MetadataNotSupported
	}
	if !frame.MediaValid() || (!frame.End && len(frame.Encoded) != 11) {
		return nil, errors.New("invalid encoded P25 media")
	}
	return marshalPacketFrame(opaqueFullRateOperation, frame)
}
func DecodeOpaqueCodecPacket(packet []byte) (Frame, error) {
	if len(packet) < packetHeaderSize || string(packet[:4]) != "DV25" || packet[4] != opaqueFullRateOperation || packet[5] != 0 || len(packet) != packetHeaderSize+int(binary.BigEndian.Uint16(packet[58:60])) || packet[60] > 1 || packet[62] != 0 || packet[63] != 0 {
		return Frame{}, errors.New("invalid native FullRate P25 packet")
	}
	flags := binary.BigEndian.Uint16(packet[10:12])
	if flags&^uint16(packetFlagEnd|packetFlagHeader) != 0 || flags&packetFlagEnd != 0 && flags != packetFlagEnd {
		return Frame{}, errors.New("invalid native FullRate P25 flags")
	}
	f := Frame{CallID: hex.EncodeToString(packet[32:48]), SourceID: int(binary.BigEndian.Uint32(packet[12:16])), TalkgroupID: int(binary.BigEndian.Uint32(packet[16:20])), Sequence: binary.BigEndian.Uint64(packet[24:32]), End: flags&packetFlagEnd != 0, Emergency: packet[60] == 1, ServiceOptions: packet[61], ManufacturerID: packet[57], AlgorithmID: packet[6], KeyID: binary.BigEndian.Uint16(packet[8:10]), VoiceIndex: packet[7], CapturedAt: time.Now()}
	f.Encrypted = p25crypto.Supported(int(f.AlgorithmID))
	if (f.ServiceOptions&0x80 != 0) != f.Emergency || (f.ServiceOptions&0x40 != 0) != f.Encrypted {
		return Frame{}, errors.New("opaque service options disagree")
	}
	for _, value := range packet[48:57] {
		if value != 0 {
			return Frame{}, errors.New("opaque FullRate packet contains reserved MI bytes")
		}
	}
	if f.End {
		if len(packet) != packetHeaderSize {
			return Frame{}, errors.New("native P25 End contains media")
		}
	} else if err := decodeFullRatePayload(&f, packet[packetHeaderSize:], flags); err != nil {
		return Frame{}, err
	}
	if f.SourceID < 1 || f.SourceID > 0xfffffb || f.TalkgroupID < 1 || f.TalkgroupID > 65534 || f.Sequence == 0 || !f.MediaValid() {
		return Frame{}, errors.New("invalid native P25 media or identity")
	}
	return f, nil
}

func marshalPacketFrame(op byte, frame Frame) ([]byte, error) {
	if op != 1 && op != 2 && op != 3 && op != opaqueFullRateOperation {
		return nil, errors.New("unsupported packet codec operation")
	}
	if len(frame.CallID) < 1 || len(frame.CallID) > 128 || frame.SourceID < 1 || frame.SourceID > 0xfffffb || frame.TalkgroupID < 1 || frame.TalkgroupID > 65534 || (!frame.End && frame.Sequence == 0) || frame.VoiceIndex > 17 || (frame.ManufacturerID != 0 && frame.ManufacturerID != 1) {
		return nil, errors.New("packet codec frame identity or sequence is invalid")
	}
	if op != 3 && ((frame.ServiceOptions&0x80 != 0) != frame.Emergency || (frame.ServiceOptions&0x40 != 0) != frame.Encrypted) {
		return nil, errors.New("P25 service options disagree with call mode")
	}
	var payload []byte
	var flags uint16
	if frame.End {
		if len(frame.PCM) != 0 || len(frame.Encoded) != 0 || frame.P25 != nil {
			return nil, errors.New("packet codec End contains media or metadata")
		}
		flags = packetFlagEnd
	} else if op == 1 {
		if len(frame.PCM) != FrameBytes || len(frame.Encoded) != 0 || frame.P25 != nil {
			return nil, errors.New("packet codec encoding requires PCM only")
		}
		payload = frame.PCM
	} else if op == 2 || op == 3 || op == opaqueFullRateOperation {
		if len(frame.PCM) != 0 || len(frame.Encoded) != 11 {
			return nil, errors.New("packet codec decoding requires encoded FullRate voice")
		}
		var err error
		payload, flags, err = fullRatePayload(frame)
		if err != nil {
			return nil, err
		}
	} else {
		return nil, errors.New("unsupported packet codec operation")
	}
	if len(frame.MessageIndicator) != 0 && len(frame.MessageIndicator) != 9 {
		return nil, errors.New("packet codec MI is invalid")
	}
	out := make([]byte, packetHeaderSize+len(payload))
	copy(out, "DV25")
	out[4], out[6], out[7] = op, frame.AlgorithmID, frame.VoiceIndex
	binary.BigEndian.PutUint16(out[8:10], frame.KeyID)
	binary.BigEndian.PutUint16(out[10:12], flags)
	binary.BigEndian.PutUint32(out[12:16], uint32(frame.SourceID))
	binary.BigEndian.PutUint32(out[16:20], uint32(frame.TalkgroupID))
	binary.BigEndian.PutUint64(out[24:32], frame.Sequence)
	identity := sha256.Sum256([]byte(frame.CallID))
	copy(out[32:48], identity[:16])
	if op == 3 {
		copy(out[48:57], frame.MessageIndicator)
	} // Explicit crypto-vector utility only.
	out[57] = frame.ManufacturerID
	if op != 3 {
		out[61] = frame.ServiceOptions
	}
	// Octet60 is the emergency indicator,61 the service octet,62-63 reserved.
	if frame.Emergency {
		out[60] = 1
	}
	binary.BigEndian.PutUint16(out[58:60], uint16(len(payload)))
	copy(out[packetHeaderSize:], payload)
	return out, nil
}

func unmarshalPacketFrame(packet []byte, input Frame, op byte) (Frame, error) {
	if len(packet) < packetHeaderSize || string(packet[:4]) != "DV25" || packet[4] != op|0x80 || len(packet) != packetHeaderSize+int(binary.BigEndian.Uint16(packet[58:60])) {
		return Frame{}, errors.New("native packet codec response is malformed")
	}
	if packet[5] != 0 {
		if packet[5] == 6 {
			return Frame{}, ErrP25MetadataNotSupported
		}
		if packet[5] == 7 {
			return Frame{}, ErrP25SynchronizationPending
		}
		if packet[5] == 2 {
			return Frame{}, errors.New("the requested radio encryption key is unavailable")
		}
		return Frame{}, fmt.Errorf("native packet codec rejected the frame (status %d)", packet[5])
	}
	identity := sha256.Sum256([]byte(input.CallID))
	if string(packet[32:48]) != string(identity[:16]) || binary.BigEndian.Uint64(packet[24:32]) != input.Sequence || int(binary.BigEndian.Uint32(packet[12:16])) != input.SourceID || int(binary.BigEndian.Uint32(packet[16:20])) != input.TalkgroupID {
		return Frame{}, errors.New("native packet codec response identity changed")
	}
	if packet[60] > 1 || (packet[60] == 1) != input.Emergency || packet[62] != 0 || packet[63] != 0 {
		return Frame{}, errors.New("native packet codec changed emergency metadata")
	}
	if packet[57] != input.ManufacturerID {
		return Frame{}, errors.New("native packet codec changed voice manufacturer metadata")
	}
	if op != 3 && packet[61] != input.ServiceOptions {
		return Frame{}, errors.New("native packet codec changed service options")
	}
	if op == 3 && packet[61] != 0 {
		return Frame{}, errors.New("crypto utility response has reserved service options")
	}
	if !input.End && (packet[6] != input.AlgorithmID || binary.BigEndian.Uint16(packet[8:10]) != input.KeyID) {
		return Frame{}, errors.New("native packet codec changed encryption parameters")
	}
	if !input.End && op != 1 && packet[7] != input.VoiceIndex {
		return Frame{}, errors.New("native packet codec changed voice index")
	}
	flags := binary.BigEndian.Uint16(packet[10:12])
	if flags&^uint16(packetFlagEnd|packetFlagHeader) != 0 || (flags&packetFlagEnd != 0) != input.End || input.End && flags != packetFlagEnd {
		return Frame{}, errors.New("native packet codec changed End/header flags")
	}
	result := input
	result.PCM, result.Encoded, result.MessageIndicator, result.P25 = nil, nil, nil, nil
	result.ManufacturerID = packet[57]
	result.ServiceOptions = packet[61]
	result.AlgorithmID, result.KeyID, result.VoiceIndex = packet[6], binary.BigEndian.Uint16(packet[8:10]), packet[7]
	result.Encrypted = p25crypto.Supported(int(result.AlgorithmID))
	if result.Encrypted && !result.End {
		result.MessageIndicator = append([]byte{}, packet[48:57]...)
	}
	if result.End {
		if len(packet) != packetHeaderSize {
			return Frame{}, errors.New("native packet codec End contains media")
		}
	} else if op == 2 {
		if flags != 0 || len(packet) != packetHeaderSize+FrameBytes {
			return Frame{}, errors.New("native PCM response contains invalid flags or media")
		}
		result.PCM = append([]byte{}, packet[packetHeaderSize:]...)
	} else if err := decodeFullRatePayload(&result, packet[packetHeaderSize:], flags); err != nil {
		return Frame{}, err
	}

	return result, nil
}

func (c *PacketCodec) transform(ctx context.Context, op byte, frame Frame) (Frame, error) {
	packet, err := marshalPacketFrame(op, frame)
	if err != nil {
		return Frame{}, err
	}
	select {
	case c.gate <- struct{}{}:
		defer func() { <-c.gate }()
	case <-ctx.Done():
		return Frame{}, ctx.Err()
	}
	c.mu.Lock()
	if c.closed || c.command == nil {
		c.mu.Unlock()
		return Frame{}, ErrUnavailable
	}
	input, output := c.input, c.output
	c.mu.Unlock()
	type response struct {
		packet []byte
		err    error
	}
	ready := make(chan response, 1)
	go func() {
		prefix := make([]byte, 4)
		binary.BigEndian.PutUint32(prefix, uint32(len(packet)))
		if _, e := input.Write(append(prefix, packet...)); e != nil {
			ready <- response{err: e}
			return
		}
		if _, e := io.ReadFull(output, prefix); e != nil {
			ready <- response{err: e}
			return
		}
		n := binary.BigEndian.Uint32(prefix)
		if n < packetHeaderSize || n > packetHeaderSize+FrameBytes {
			ready <- response{err: errors.New("invalid response size")}
			return
		}
		buffer := make([]byte, n)
		_, e := io.ReadFull(output, buffer)
		ready <- response{buffer, e}
	}()
	timer := time.NewTimer(2 * time.Second)
	defer timer.Stop()
	select {
	case value := <-ready:
		if value.err != nil {
			_ = c.Close()
			return Frame{}, errors.New("native packet codec connection failed")
		}
		result, err := unmarshalPacketFrame(value.packet, frame, op)
		if err != nil && len(value.packet) > 5 && value.packet[5] == 0 {
			_ = c.Close()
		}
		return result, err
	case <-ctx.Done():
		_ = c.Close()
		return Frame{}, ctx.Err()
	case <-timer.C:
		_ = c.Close()
		return Frame{}, errors.New("native packet codec timed out")
	}
}

// Alive reports process supervision state without issuing a codec request.
func (c *PacketCodec) Alive() bool {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.closed || c.command == nil || c.done == nil {
		return false
	}
	select {
	case <-c.done:
		return false
	default:
		return true
	}
}

func (c *PacketCodec) Close() error {
	return c.closeWithTimeout(time.Second)
}

func (c *PacketCodec) closeWithTimeout(timeout time.Duration) error {
	c.closeOnce.Do(func() {
		deadline := time.Now().Add(timeout)
		c.mu.Lock()
		c.closed = true
		command, input, output, done := c.command, c.input, c.outputPipe, c.done
		c.mu.Unlock()
		if input != nil {
			_ = input.Close()
		}
		if output != nil {
			_ = output.Close()
		}
		if command != nil && command.Process != nil && !codecDone(done) {
			signalCodecProcess(command.Process, syscall.SIGKILL)
		}
		if !waitCodecDone(done, deadline) {
			c.closeError = errors.New("native packet audio process did not stop")
		}
	})
	return c.closeError
}
