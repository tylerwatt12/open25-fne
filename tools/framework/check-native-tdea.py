#!/usr/bin/env python3
"""Check native three-key TDEA against independently published Phase1 vectors.

Only starts local --packet-codec subprocesses and OpenSSL; no devices/network.
Expected values in internal/p25crypto/testdata/phase1-tdea-published-vectors.json are
transcribed from AAAD-B B.4, not generated by the native implementation.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]


def packet(vector, kid=0, algorithm=0x83, mi=None, index=None):
    # Current DV25 op3 carries a FullRate block, not a bare 11-byte IMBE word.
    # Engineering contract: internal/p25rtp/{types,codec}.go and native FullRate.h.
    types = bytes.fromhex('c2 c3 c4 c5 c6 c7 c8 c9 6a cb cc 6d 6e 6f 70 71 72 73')
    position = vector['index']
    voice = bytes([types[position]]) + bytes.fromhex(vector['plain']) + bytes(2)
    if position in (8, 17):
        voice += bytes(3)  # Supplied zero LSD and status.
    elif 11 <= position <= 16:
        voice += bytes(4)  # Supplied zero ES symbols and status.
    value = bytearray(64 + len(voice))
    value[:4] = b'DV25'
    value[4], value[6], value[7] = 3, algorithm, vector['index'] if index is None else index
    struct.pack_into('>HII', value, 10, 0, 10003, 1001)
    struct.pack_into('>H', value, 8, kid)
    struct.pack_into('>Q', value, 24, vector['index'] + 1)
    value[32:48] = hashlib.sha256(f'tdea-{algorithm}-{kid}'.encode()).digest()[:16]
    value[48:57] = mi if mi is not None else bytes.fromhex('1234567890ABCDEF00')
    struct.pack_into('>H', value, 58, len(voice))
    value[64:] = voice
    return struct.pack('>I', len(value)) + value


def responses(data):
    out = []
    cursor = 0
    while cursor < len(data):
        assert len(data) - cursor >= 4, 'short response prefix'
        size = struct.unpack_from('>I', data, cursor)[0]
        cursor += 4
        assert size >= 64 and size <= len(data) - cursor, 'invalid response length'
        out.append(data[cursor:cursor + size])
        cursor += size
    return out


def run(binary, material, request):
    with tempfile.TemporaryDirectory(prefix='p25-public-tdea-') as folder:
        path = Path(folder) / 'public-keys'
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, 'w') as stream:
            stream.write(material)
        return subprocess.run([str(binary), '--packet-codec', str(path)], input=request,
                              capture_output=True, timeout=30, check=False)


def check(binary):
    binary = Path(binary).resolve(strict=True)
    fixture = ROOT / 'internal/p25crypto/testdata/phase1-tdea-published-vectors.json'
    vectors = json.loads(fixture.read_text())
    key, mi = vectors['key'], vectors['mi']
    # Independent OpenSSL OFB implementation verifies every published 64-bit
    # output register; no native function supplies the oracle.
    oracle = subprocess.run([shutil.which('openssl') or '/usr/bin/openssl', 'enc',
                             '-des-ede3-ofb', '-K', key, '-iv', mi[:16], '-nopad'],
                            input=bytes(224), capture_output=True, timeout=10, check=True)
    expected_stream = bytes.fromhex(''.join(vectors['output_registers']))
    assert oracle.stdout == expected_stream, 'published TDEA output register disagreement'
    for row in vectors['voice']:
        i = row['index']
        offset = 19 + i % 9 * 11 + (101 if i >= 9 else 0) + (2 if i % 9 == 8 else 0)
        transformed = bytes(a ^ b for a, b in zip(bytes.fromhex(row['plain']), oracle.stdout[offset:]))
        assert transformed == bytes.fromhex(row['cipher']), f'published word {i} disagrees'
    keys = f'131:0:{key}\n131:7:{key}\n129:0:0123456789ABCDEF\n'
    operations = []
    for kid in (0, 7):
        for row in vectors['voice']:
            request = packet(row, kid)
            body = request[68:]
            expected = body[:1] + bytes.fromhex(row['cipher']) + body[12:]
            operations.append((request, expected, 0))
    # Same numerical KID under DES must select the independent DES identity.
    des_first = bytes.fromhex('CFAA74B68C19F9D1BC82B1')  # AAAD-B A.4 PDF42/printed32.
    des_request = packet(vectors['voice'][0], algorithm=0x81)
    operations.append((des_request, des_request[68:69] + des_first + des_request[80:], 0))
    for invalid in (bytes(9), bytes(8) + b'\x01'):
        operations.append((packet(vectors['voice'][0], mi=invalid), None, 1))
    operations.append((packet(vectors['voice'][0], kid=8), None, 2))
    operations.append((packet(vectors['voice'][0], index=18), None, 1))
    # The retired metadata-free format remains rejected; no compatibility path.
    legacy = bytearray(packet(vectors['voice'][0])[4:68])
    struct.pack_into('>H', legacy, 58, 11)
    legacy += bytes.fromhex(vectors['voice'][0]['plain'])
    operations.append((struct.pack('>I', len(legacy)) + legacy, None, 6))
    result = run(binary, keys, b''.join(request for request, _, _ in operations))
    assert result.returncode == 0, 'native codec process failed'
    values = responses(result.stdout)
    assert len(values) == len(operations), 'missing codec response'
    for response, (request, expected, status) in zip(values, operations):
        assert response[:4] == b'DV25' and response[4] == 0x83
        assert response[5] == status, f'unexpected codec status {response[5]}, expected {status}'
        assert response[6:58] == request[10:62], 'voice identity or MI changed'
        if expected is None:
            assert len(response) == 64, 'rejected input returned media'
        else:
            assert response[64:] == expected, 'published cipher or FullRate metadata disagreement'
            assert struct.unpack_from('>H', response, 58)[0] == len(expected)
    raw = bytes.fromhex(key)
    invalid_keys = [raw[:size] for size in (0, 8, 16, 23)] + [raw + b'\x00']
    for first in range(3):
        for second in range(first + 1, 3):
            for parity in (0, 1):
                invalid = bytearray(raw)
                invalid[second*8:second*8+8] = bytes(v ^ parity for v in raw[first*8:first*8+8])
                invalid_keys.append(invalid)
    for invalid in invalid_keys:
        result = run(binary, f'131:0:{invalid.hex()}\n', b'')
        assert result.returncode == 2 and not result.stdout, 'invalid key file accepted'
    parity = bytes(v ^ 1 for v in raw)
    result = run(binary, f'131:0:{parity.hex()}\n', packet(vectors['voice'][0]))
    assert result.returncode == 0
    parity_response = responses(result.stdout)[0]
    assert parity_response[5] == 0 and parity_response[65:76] == bytes.fromhex(vectors['voice'][0]['cipher'])
    return {'passed': True, 'scope': 'Current structured FullRate native packet codec and independent OpenSSL oracle; no RF/subscriber qualification',
            'published_output_registers': 28, 'published_voice_words': 18,
            'native_voice_checks': 36, 'same_kid_different_algorithm_checks': 1,
            'malformed_packet_checks': 5, 'legacy_raw11_rejected': True, 'invalid_key_file_checks': len(invalid_keys),
            'parity_invariance_checked': True, 'fixture_sha256': hashlib.sha256(fixture.read_bytes()).hexdigest(),
            'binary_sha256': hashlib.sha256(binary.read_bytes()).hexdigest(),
            'checker_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('binary')
    args = parser.parse_args()
    print(json.dumps(check(args.binary), indent=2))
