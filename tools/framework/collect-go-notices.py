#!/usr/bin/env python3
"""Collect unchanged notices from the Go packages used by the ARM64 executable."""

import argparse
import json
import os
from pathlib import Path
import subprocess


def json_objects(text):
    decoder = json.JSONDecoder()
    while text.strip():
        text = text.lstrip()
        value, end = decoder.raw_decode(text)
        yield value
        text = text[end:]


def notice_files(directory):
    names = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "PATENTS")
    return sorted(
        path for path in directory.iterdir()
        if path.is_file() and any(
            path.name.upper() == name or path.name.upper().startswith(name + suffix)
            for name in names for suffix in (".", "-", "_")
        )
    )


def collect(repo):
    env = {**os.environ, "CGO_ENABLED": "0", "GOOS": "linux", "GOARCH": "arm64"}
    result = subprocess.run(
        ["go", "list", "-mod=readonly", "-deps", "-json", "./cmd/open25-fne"],
        cwd=repo, env=env, text=True, capture_output=True, check=True,
    )
    goroot = Path(subprocess.check_output(
        ["go", "env", "GOROOT"], cwd=repo, env=env, text=True,
    ).strip())
    goversion = subprocess.check_output(
        ["go", "env", "GOVERSION"], cwd=repo, env=env, text=True,
    ).strip()
    components = {f"Go {goversion}": (goroot, {goroot})}
    for package in json_objects(result.stdout):
        module = package.get("Module")
        if module and not module.get("Main"):
            source = module.get("Replace", module)
            root = Path(source["Dir"])
            label = f"{module['Path']}@{module['Version']}"
            if "Replace" in module:
                label += f" (replacement: {source['Path']} {source.get('Version', '')})"
            _, directories = components.setdefault(label, (root, {root}))
        elif package.get("Standard"):
            root, directories = components[f"Go {goversion}"]
        else:
            continue
        directory = Path(package["Dir"])
        if not directory.is_relative_to(root):
            raise ValueError(f"Package directory is outside its source root: {package['ImportPath']}")
        while directory != root:
            directories.add(directory)
            directory = directory.parent

    output = [
        "Go runtime and dependency notices for Open25 FNE\n",
        "Target: linux/arm64, CGO_ENABLED=0\n",
        "Generated by tools/framework/collect-go-notices.py from the selected Go package graph.\n",
        "Upstream notice files are reproduced unchanged; some also describe source/test materials.\n",
    ]
    for label, (root, directories) in sorted(components.items()):
        files = sorted({path for directory in directories for path in notice_files(directory)})
        if not files:
            raise ValueError(f"No license or notice files found for {label}")
        output.append(f"\n===== {label} =====\n")
        for path in files:
            output.append(f"\n--- {path.relative_to(root).as_posix()} ---\n")
            output.append(path.read_text())
            output.append("\n")
    return "".join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    repo = Path(__file__).resolve().parents[2]
    text = collect(repo)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)
    print(f"Go dependency notices collected: {args.output}")


if __name__ == "__main__":
    main()
